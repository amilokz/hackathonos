/** Lucide-style stroke icon — 24 viewBox, consistent 2px stroke. */
export function DashIcon({ name, className = 'h-5 w-5' }: { name: DashIconName; className?: string }) {
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={2}
      strokeLinecap="round"
      strokeLinejoin="round"
      className={className}
      aria-hidden="true"
    >
      {PATHS[name]}
    </svg>
  );
}

export type ChipTint = 'indigo' | 'emerald' | 'amber' | 'violet' | 'sky' | 'slate' | 'teal' | 'red';

const TINTS: Record<ChipTint, string> = {
  indigo: 'bg-indigo-100 text-indigo-600',
  emerald: 'bg-emerald-100 text-emerald-600',
  amber: 'bg-amber-100 text-amber-600',
  violet: 'bg-violet-100 text-violet-600',
  sky: 'bg-sky-100 text-sky-600',
  slate: 'bg-slate-100 text-slate-500',
  teal: 'bg-teal-100 text-teal-600',
  red: 'bg-red-100 text-red-600',
};

/** Small tinted SVG icon chip used for section headers and list rows. */
export function IconChip({
  icon,
  tint = 'indigo',
  size = 'md',
  className = '',
}: {
  icon: DashIconName;
  tint?: ChipTint;
  size?: 'sm' | 'md' | 'lg';
  className?: string;
}) {
  const sizes = {
    sm: 'h-8 w-8 rounded-lg [&_svg]:h-4 [&_svg]:w-4',
    md: 'h-10 w-10 rounded-xl [&_svg]:h-5 [&_svg]:w-5',
    lg: 'h-14 w-14 rounded-2xl [&_svg]:h-7 [&_svg]:w-7',
  };
  return (
    <span
      className={`inline-flex shrink-0 items-center justify-center ${sizes[size]} ${TINTS[tint]} ${className}`}
      aria-hidden="true"
    >
      <DashIcon name={icon} />
    </span>
  );
}

/** Section card header: SVG icon chip + title + optional meta + right-side link. */
